#!/usr/bin/env node
// Regenerates src/index.ts from the export lists of every component, hook and lib file.
// Run after adding a component: `pnpm gen`.
import { readdirSync, readFileSync, writeFileSync } from "node:fs"
import { join, relative } from "node:path"
import { fileURLToPath } from "node:url"

const root = fileURLToPath(new URL("../src/", import.meta.url))
const groups = [
  ["Theme", "components/theme"],
  ["Primitives (shadcn/ui, restyled)", "components/ui"],
  ["Admin and layout", "components/admin"],
  ["Layout and text", "components/layout"],
  ["Data display", "components/data"],
  ["AI and chat", "components/ai"],
  ["Auth", "components/auth"],
  ["Hooks", "hooks"],
  ["Utilities", "lib"],
]

const out = ["// Generated by scripts/gen-index.mjs. Do not edit; run `pnpm gen`.", ""]
for (const [title, dir] of groups) {
  out.push(`// ${title}`)
  for (const file of readdirSync(join(root, dir)).sort()) {
    if (!/\.tsx?$/.test(file) || file.endsWith(".test.tsx")) continue
    const path = join(root, dir, file)
    const text = readFileSync(path, "utf8")
    const spec = `./${relative(root, path).replace(/\.tsx?$/, "")}`
    const values = new Set()
    const types = new Set()
    for (const m of text.matchAll(/^export \{([^}]*)\}/gm))
      for (const n of m[1]
        .split(",")
        .map((s) => s.trim())
        .filter(Boolean))
        values.add(n)
    for (const m of text.matchAll(/^export (?:async )?(?:function|const|class) (\w+)/gm)) values.add(m[1])
    for (const m of text.matchAll(/^export (?:type|interface) (\w+)/gm)) types.add(m[1])
    if (values.size) out.push(`export { ${[...values].join(", ")} } from "${spec}"`)
    if (types.size) out.push(`export type { ${[...types].join(", ")} } from "${spec}"`)
  }
  out.push("")
}
writeFileSync(join(root, "index.ts"), out.join("\n"))
console.log("wrote src/index.ts")
